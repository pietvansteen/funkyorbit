/* Funky Orbit — builds the "Siteswap" motion graphics template in After Effects and exports it as .mogrt.
   Generated by make_mogrt.py, which fills in the colour tables from the Sheet; run that, not this file. */
(function () {
  var TABLE = "__TABLE__";      // siteswap:CODE,...            from the "Kleuren" tab
  var SYNC = "__SYNC__";        // a/b:CODEA/CODEB;...          from the "Kleuren sync" tab
  var MAX = __MAX__;            // number of boxes in the template
  var OUT_MOGRT = "__OUT_MOGRT__";  // folder; AE names the file after the template
  var OUT_AEP = "__OUT_AEP__";
  var FONT = "IBMPlexMono-SemiBold";
  var W = 1920, H = 1080, FPS = 25, DUR = 6, INTRO = 0.7, OUTRO = 0.4;

  app.beginSuppressDialogs();
  if (app.project) app.project.close(CloseOptions.DO_NOT_SAVE_CHANGES);
  app.newProject();
  var comp = app.project.items.addComp("Funky Orbit siteswap", W, H, 1, DUR, FPS);

  function hex(h) { return [parseInt(h.substr(1, 2), 16) / 255, parseInt(h.substr(3, 2), 16) / 255, parseInt(h.substr(5, 2), 16) / 255]; }

  // ---- Controls ---------------------------------------------------------------------------------
  var ctl = comp.layers.addNull();
  ctl.name = "Controls";
  ctl.enabled = false;
  var fx = ctl.property("ADBE Effect Parade");
  function effect(match, name) { var e = fx.addProperty(match); e.name = name; return e; }
  // Sliders in a mogrt run 0-100, so Grootte is scaled: 40 = 96 px boxes, 100 = 240 px.
  effect("ADBE Slider Control", "Grootte").property(1).setValue(40);
  effect("ADBE Point Control", "Positie").property(1).setValue([W / 2, H - 150]);
  // setPropertyParameters replaces the effect, which loses its name: rename it via the returned menu.
  var menu = effect("ADBE Dropdown Control", "Uitlijning").property(1).setPropertyParameters(["Links", "Midden", "Rechts"]);
  menu.propertyGroup(1).name = "Uitlijning";
  menu.setValue(2);
  effect("ADBE Checkbox Control", "Animatie").property(1).setValue(1);
  effect("ADBE Slider Control", "Schaduw").property(1).setValue(40);
  var intro = effect("ADBE Slider Control", "Intro").property(1);
  intro.setValueAtTime(0, 0); intro.setValueAtTime(INTRO, 1);
  var outro = effect("ADBE Slider Control", "Outro").property(1);
  outro.setValueAtTime(DUR - OUTRO, 1); outro.setValueAtTime(DUR, 0);

  // ---- Input text layers (hidden; edited from Premiere) -----------------------------------------
  function textLayer(name, value) {
    var l = comp.layers.addText(value);
    l.name = name;
    var td = l.property("ADBE Text Properties").property("ADBE Text Document").value;
    td.font = FONT; td.fontSize = 100; td.applyFill = true; td.fillColor = [1, 1, 1]; td.applyStroke = false;
    td.justification = ParagraphJustification.CENTER_JUSTIFY;
    l.property("ADBE Text Properties").property("ADBE Text Document").setValue(td);
    return l;
  }
  var inSS = textLayer("Siteswap", "b97");
  var inKC = textLayer("Kleurcode", "auto");
  inSS.enabled = false; inKC.enabled = false;

  // ---- Data: parses the input once and lays out the boxes, as JSON ------------------------------
  var data = textLayer("Data", "{}");
  data.enabled = false;
  data.property("ADBE Text Properties").property("ADBE Text Document").expression = [
    'var T = "' + TABLE + '";',
    'var S = "' + SYNC + '";',
    'function trim(s) { return s.replace(/^\\s+|\\s+$/g, ""); }',
    'var raw = trim(("" + thisComp.layer("Siteswap").text.sourceText).toLowerCase()).replace(/\\s*[|\\/]\\s*/g, " ");',
    'var kc = trim(("" + thisComp.layer("Kleurcode").text.sourceText).toUpperCase());',
    'var c = thisComp.layer("Controls");',
    'var Hb = c.effect("Grootte")(1).value * 2.4, P = c.effect("Positie")(1).value, A = c.effect("Uitlijning")(1).value;',
    'function rot(a, k) { return a.slice(k).concat(a.slice(0, k)); }',
    'function tokens(s) { return s.match(/[0-9a-z]p?/g) || []; }',
    'var parts = raw.split(/\\s+/), jug = [], cols = [];',
    'if (parts.length > 1) {',
    '  jug = [tokens(parts[0]), tokens(parts[1])];',
    '  var ka = jug[0].join(","), kb = jug[1].join(","), found = null;',
    '  var rows = S.split(";");',
    '  for (var r = 0; r < rows.length && !found; r++) {',
    '    var f = rows[r].split(":"), pat = f[0].split("/"), code = f[1].split("/");',
    '    var ea = tokens(pat[0]), eb = tokens(pat[1]), ca = code[0].split(""), cb = code[1].split("");',
    '    for (var sw = 0; sw < 2 && !found; sw++) {',
    '      var xa = sw ? eb : ea, xb = sw ? ea : eb, ya = sw ? cb : ca, yb = sw ? ca : cb;',
    '      if (xa.length != jug[0].length || xb.length != jug[1].length) continue;',
    '      for (var k = 0; k < xa.length; k++) {',
    '        if (rot(xa, k).join(",") == ka && rot(xb, k).join(",") == kb) { found = [rot(ya, k), rot(yb, k)]; break; }',
    '      }',
    '    }',
    '  }',
    '  var ov = kc.split(/\\s+/);',
    '  if (/^[WBOR ]+$/.test(kc) && ov.length == 2) found = [ov[0].split(""), ov[1].split("")];',
    '  cols = found || [[], []];',
    '} else {',
    '  jug = [raw.replace(/\\s/g, "").split("")];',
    '  var s = jug[0].join(""), n0 = s.length, hit = null;',
    '  if (/^[WBOR]+$/.test(kc)) hit = kc;',
    '  else if (n0) {',
    '    var re = new RegExp("(^|,)([^:,]{" + n0 + "}):([WBOR]{" + n0 + "})", "g"), m, map = {};',
    '    while ((m = re.exec(T))) map[m[2]] = m[3];',
    '    for (var k = 0; k < n0 && !hit; k++) {',
    '      var code = map[s.slice(k) + s.slice(0, k)];',
    '      if (code) hit = code.slice(n0 - k) + code.slice(0, n0 - k);',
    '    }',
    '  }',
    '  cols = [(hit || "").split("")];',
    '}',
    'var F = Hb * 0.56, gap = Hb * 0.09, sepW = Hb * 0.06, sepM = Hb * 0.3;',
    'var boxes = [], x = 0, sep = null;',
    'for (var j = 0; j < jug.length; j++) {',
    '  if (j) { sep = x + sepM - gap + sepW / 2; x += 2 * sepM + sepW - gap; }',
    '  for (var i = 0; i < jug[j].length; i++) {',
    '    var t = jug[j][i], w = Math.max(Hb * 0.84, t.length * 0.6 * F + 0.5 * F);',
    '    boxes.push({ t: t, c: cols[j][i] || "", x: x + w / 2, w: w });',
    '    x += w + gap;',
    '  }',
    '}',
    'var total = Math.max(0, x - gap), x0 = A == 1 ? P[0] : A == 2 ? P[0] - total / 2 : P[0] - total;',
    'for (var b = 0; b < boxes.length; b++) boxes[b].x += x0;',
    'JSON.stringify({ n: boxes.length, H: Hb, F: F, y: P[1], boxes: boxes, sep: sep === null ? null : sep + x0 });'
  ].join("\n");

  // ---- Shared expression snippets ---------------------------------------------------------------
  var READ = 'var d = JSON.parse("" + thisComp.layer("Data").text.sourceText); ';
  // pop-in progress for box I (0..1, eased with a little overshoot)
  var POP = 'function pop(I) { var c = thisComp.layer("Controls"); if (!c.effect("Animatie")(1).value) return 1; ' +
    'var k = 0.18, p = c.effect("Intro")(1).value * (1 + Math.max(0, d.n - 1) * k) - I * k; p = Math.min(1, Math.max(0, p)); ' +
    'var c1 = 1.70158, c3 = c1 + 1; return p >= 1 ? 1 : 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2); } ';
  var FADE = 'function fade(I) { var c = thisComp.layer("Controls"); if (!c.effect("Animatie")(1).value) return 100; ' +
    'var k = 0.18, p = c.effect("Intro")(1).value * (1 + Math.max(0, d.n - 1) * k) - I * k; ' +
    'return 100 * Math.min(1, Math.max(0, p * 4)) * c.effect("Outro")(1).value; } ';
  var BG = { W: "#eeeff2", B: "#1f4fd1", O: "#ee5a2c", R: "#e6386a", "": "#e3e7f0" };
  var FG = { W: "#15203b", B: "#ffffff", O: "#ffffff", R: "#ffffff", "": "#15203b" };
  function colorExpr(table) {
    var parts = [];
    for (var k in table) { var c = hex(table[k]); parts.push('"' + k + '":[' + c.join(",") + ',1]'); }
    return '({' + parts.join(",") + '})';
  }

  // ---- Separator between the two jugglers (sync patterns) ---------------------------------------
  var sepL = comp.layers.addShape();
  sepL.name = "Scheiding";
  var sg = sepL.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group");
  var sr = sg.property("ADBE Vectors Group").addProperty("ADBE Vector Shape - Rect");
  sr.property("ADBE Vector Rect Size").expression = READ + '[d.H * 0.06, d.H * 0.9]';
  sr.property("ADBE Vector Rect Roundness").expression = READ + 'd.H * 0.03';
  var sf = sg.property("ADBE Vectors Group").addProperty("ADBE Vector Graphic - Fill");
  sf.property("ADBE Vector Fill Color").setValue([1, 1, 1]);
  sepL.property("ADBE Transform Group").property("ADBE Position").expression = READ + 'd.sep === null ? [-1000, -1000] : [d.sep, d.y]';
  sepL.property("ADBE Transform Group").property("ADBE Opacity").expression = READ + FADE + 'd.sep === null ? 0 : fade(0) * 0.85';
  var sds = sepL.property("ADBE Effect Parade").addProperty("ADBE Drop Shadow");
  sds.property("ADBE Drop Shadow-0002").expression = 'thisComp.layer("Controls").effect("Schaduw")(1).value * 2.55';
  sds.property("ADBE Drop Shadow-0004").setValue(3);
  sds.property("ADBE Drop Shadow-0005").setValue(14);

  // ---- The boxes --------------------------------------------------------------------------------
  for (var i = MAX - 1; i >= 0; i--) {
    var box = comp.layers.addShape();
    box.name = "Vak " + (i + 1);
    var g = box.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group");
    var rect = g.property("ADBE Vectors Group").addProperty("ADBE Vector Shape - Rect");
    rect.property("ADBE Vector Rect Size").expression = READ + 'var b = d.boxes[' + i + ']; b ? [b.w, d.H] : [0, 0]';
    rect.property("ADBE Vector Rect Roundness").expression = READ + 'd.H * 0.14';
    var fill = g.property("ADBE Vectors Group").addProperty("ADBE Vector Graphic - Fill");
    fill.property("ADBE Vector Fill Color").expression = READ + 'var b = d.boxes[' + i + ']; ' + colorExpr(BG) + '[b ? b.c : ""]';
    var tr = box.property("ADBE Transform Group");
    tr.property("ADBE Position").expression = READ + 'var b = d.boxes[' + i + ']; b ? [b.x, d.y] : [-1000, -1000]';
    tr.property("ADBE Scale").expression = READ + POP + 'var s = 100 * pop(' + i + '); [s, s]';
    tr.property("ADBE Opacity").expression = READ + FADE + 'd.boxes[' + i + '] ? fade(' + i + ') : 0';
    var ds = box.property("ADBE Effect Parade").addProperty("ADBE Drop Shadow");
    ds.property("ADBE Drop Shadow-0002").expression = 'thisComp.layer("Controls").effect("Schaduw")(1).value * 2.55';
    ds.property("ADBE Drop Shadow-0004").setValue(4);
    ds.property("ADBE Drop Shadow-0005").setValue(18);

    var digit = textLayer("Worp " + (i + 1), "0");
    digit.moveBefore(box);
    digit.parent = box;
    digit.property("ADBE Text Properties").property("ADBE Text Document").expression =
      READ + 'var b = d.boxes[' + i + ']; b ? b.t : ""';
    var dtr = digit.property("ADBE Transform Group");
    dtr.property("ADBE Anchor Point").setValue([0, 0]);
    dtr.property("ADBE Position").expression = READ + '[0, d.F * 0.36]';
    dtr.property("ADBE Scale").expression = READ + 'var s = d.F; [s, s]';
    dtr.property("ADBE Opacity").expression = READ + FADE + 'd.boxes[' + i + '] ? fade(' + i + ') : 0';
    var dfill = digit.property("ADBE Effect Parade").addProperty("ADBE Fill");
    dfill.property("ADBE Fill-0002").expression = READ + 'var b = d.boxes[' + i + ']; ' + colorExpr(FG) + '[b ? b.c : ""]';
  }

  // ---- Responsive time: keep the intro and outro intact when the clip is stretched in Premiere ---
  function region(t, len, name) {
    var mv = new MarkerValue(name);
    mv.duration = len;
    mv.protectedRegion = true;
    comp.markerProperty.setValueAtTime(t, mv);
  }
  region(0, INTRO, "Intro");
  region(DUR - OUTRO, OUTRO, "Outro");

  // ---- Essential Graphics -----------------------------------------------------------------------
  comp.motionGraphicsTemplateName = "Funky Orbit siteswap";
  comp.openInEssentialGraphics();
  inSS.property("ADBE Text Properties").property("ADBE Text Document").addToMotionGraphicsTemplateAs(comp, "Siteswap");
  inKC.property("ADBE Text Properties").property("ADBE Text Document").addToMotionGraphicsTemplateAs(comp, "Kleurcode (auto = uit de Sheet)");
  var names = ["Grootte", "Positie", "Uitlijning", "Animatie", "Schaduw"];
  for (var n = 0; n < names.length; n++) fx.property(names[n]).property(1).addToMotionGraphicsTemplateAs(comp, names[n]);

  // Read the font before saving: after the save/export the layer and comp objects are no longer valid.
  var font = inSS.property("ADBE Text Properties").property("ADBE Text Document").value.font;
  comp.time = 2;
  app.project.save(new File(OUT_AEP));
  var ok = comp.exportAsMotionGraphicsTemplate(true, OUT_MOGRT);
  app.endSuppressDialogs(false);

  var log = new File(OUT_AEP.replace(/\.aep$/, ".log"));
  log.open("w"); log.write("export=" + ok + "\nfont=" + font + "\n"); log.close();
})();
